#!/usr/bin/env node
/**
 * Mirror public/sitemap.xml into public/sitemap-all.xml.
 *
 * Why this exists
 * ---------------
 * Google Search Console has reported "Couldn't fetch / 无法读取此站点地图" for
 * https://geoscore.help/sitemap.xml since 2026-07-20, while every other consumer
 * of the same file works: the live URL returns HTTP 200 application/xml with 50
 * <loc> entries, GSC's own "Test live URL" reports a successful fetch, Bing
 * returns Success with 50 URLs discovered, and Cloudflare logs zero blocked
 * requests for the path.
 *
 * Measured 2026-11-27, the URL also answers conditional requests with
 * `304 Not Modified` and an empty body, and the same ETag is served as weak
 * under gzip and strong under identity. A cached validator from the original
 * failed fetch therefore keeps GSC on an empty response, and resubmitting the
 * same path (including query variants such as ?v=2) never clears it.
 *
 * The fix is a second, never-submitted path with identical content so Search
 * Console has nothing stale to revalidate. Google explicitly discourages
 * wrapping a single sitemap in a <sitemapindex>, so this is a real <urlset>
 * mirror rather than an index.
 *
 * The mirror is regenerated on every build so the two files cannot drift.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
export const REPO_ROOT = path.resolve(__dirname, '..');
export const SOURCE_PATH = path.join(REPO_ROOT, 'public', 'sitemap.xml');
export const MIRROR_PATH = path.join(REPO_ROOT, 'public', 'sitemap-all.xml');

/** Extract the ordered list of <loc> values from a sitemap XML document. */
export function extractLocs(xml) {
  if (typeof xml !== 'string' || !xml.trim()) throw new Error('sitemap XML is empty');
  const locs = [];
  const re = /<loc>\s*([^<\s]+)\s*<\/loc>/gi;
  let m;
  while ((m = re.exec(xml)) !== null) locs.push(m[1].trim());
  if (locs.length === 0) throw new Error('no <loc> entries found');
  // A truncated source that still contains <urlset and a few complete <loc>
  // entries would otherwise mirror silently as a valid-looking sitemap. Require
  // the closing tag so a half-written file fails the build instead.
  if (!/<\/urlset>\s*$/.test(xml.trim())) {
    throw new Error('sitemap XML is truncated: missing closing </urlset>');
  }
  return locs;
}

/**
 * Rewrite the source sitemap for the mirror path.
 *
 * The body is copied verbatim: the mirror must advertise exactly the canonical
 * URLs (https://geoscore.help/...), never the mirror's own path. Only the
 * leading explanatory comment is adjusted so a reader of the deployed file
 * knows why two identical sitemaps exist.
 */
export function buildMirrorXml(sourceXml) {
  const locs = extractLocs(sourceXml);
  const header = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!--',
    '  Mirror of /sitemap.xml, published at a path Search Console has never seen.',
    '  /sitemap.xml stays canonical for robots.txt, Bing, IndexNow and AI crawlers.',
    '  Content is regenerated from /sitemap.xml on every build by',
    '  scripts/sync-sitemap-all.mjs — do not edit this file by hand.',
    `  URLs: ${locs.length}`,
    '-->',
  ].join('\n');
  // Drop the source document's own leading comment block, keep <urlset> onwards.
  const urlsetIndex = sourceXml.indexOf('<urlset');
  if (urlsetIndex === -1) throw new Error('sitemap XML has no <urlset> element');
  return `${header}\n${sourceXml.slice(urlsetIndex)}`;
}

export function writeMirror() {
  const sourceXml = fs.readFileSync(SOURCE_PATH, 'utf8');
  const mirrorXml = buildMirrorXml(sourceXml);
  fs.writeFileSync(MIRROR_PATH, mirrorXml, 'utf8');
  return { count: extractLocs(mirrorXml).length, outputPath: MIRROR_PATH };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { count, outputPath } = writeMirror();
    console.log(`sitemap-all.xml synced (${count} URLs) -> ${outputPath}`);
  } catch (err) {
    console.error('sitemap-all sync failed:', err.message);
    process.exit(1);
  }
}